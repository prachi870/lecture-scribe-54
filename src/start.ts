import { createStart, createMiddleware } from "@tanstack/react-start";

import { renderErrorPage } from "./lib/error-page";
import { attachSupabaseAuth } from "@/integrations/supabase/auth-attacher";

const errorMiddleware = createMiddleware().server(async ({ next }) => {
  try {
    return await next();
  } catch (error) {
    if (error != null && typeof error === "object" && "statusCode" in error) {
      throw error;
    }
    // Promote auth errors to proper 401 so TanStack Start serialises them correctly
    // instead of wrapping them in a 500 HTML page that breaks the client RPC parser.
    if (
      error instanceof Error &&
      error.message.startsWith("Unauthorized:")
    ) {
      const authError = Object.assign(new Error(error.message), { statusCode: 401 });
      throw authError;
    }
    console.error(error);
    return new Response(renderErrorPage(), {
      status: 500,
      headers: { "content-type": "text/html; charset=utf-8" },
    });
  }
});

export const startInstance = createStart(() => ({
  functionMiddleware: [attachSupabaseAuth],
  requestMiddleware: [errorMiddleware],
}));
